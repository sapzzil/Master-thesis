def t45(s):
    import re, csv
    from decimal import Decimal, ROUND_HALF_UP
    M = {'chronos_t5_base': 'Chronos-T5', 'chronos2': 'Chronos-2', 'timesfm25': 'TimesFM-2.5', 'moirai2': 'Moirai-2', 'rw': '과거변동(RW)', 'garch_t': 'GARCH-t'}
    R = {}
    for r in csv.DictReader(open(CSV, encoding='utf-8-sig')):
        cond = ('한 달' if r['L'] == '21' else '1년') + '·' + ('수익률' if r['input'] == 'return' else '가격')
        R[(M[r['model']], cond)] = [r['deficit_' + k] for k in ('CL', 'TL', 'RF', 'RS')]
    out = []; n = 0
    for l in s.split('\n'):
        cells = l.split('|')
        key = (cells[1].strip(), cells[2].strip()) if len(cells) == 12 else None
        if key in R and re.fullmatch(r'[+\-]?\d+\.\d', cells[3].strip()):
            for j, d in zip((3, 4, 5, 6), R[key]):
                old = float(cells[j].strip())
                cov = Decimal(80) - Decimal(d) * 100
                cov = cov.quantize(Decimal('1E-8')).quantize(Decimal('0.1'), rounding=ROUND_HALF_UP)
                assert abs(float(cov) - (80 - old)) <= 0.1001, (key, cov, old)
                cells[j] = f' {cov} '
            l = '|'.join(cells); n += 1
        out.append(l)
    return '\n'.join(out), n

