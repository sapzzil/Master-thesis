def box(t, b, cls=''):
    c = ('box left ' + cls).strip()
    return (f'<div class="{c}" style="padding:14px 22px;gap:10px;"><p class="bt" style="font-size:31px;">{t}</p>'
            f'<p class="bd" style="font-size:28px;color:#2B2F36;line-height:1.5;">{b}</p></div>')


def grid(items, n):
    cols = ' '.join(['1fr'] * n)
    rows = (len(items) + n - 1) // n
    inner = '\n'.join(box(*it) for it in items)
    return (f'<div style="display:grid;grid-template-columns:{cols};grid-auto-rows:1fr;gap:16px;flex:1;">\n{inner}\n</div>')


def table(head_row, rows, widths=None):
    th = ''.join(f'<th>{h}</th>' for h in head_row)
    trs = '\n'.join('<tr>' + ''.join(f'<td>{c}</td>' for c in r) + '</tr>' for r in rows)
    return f'<table class="tbl" style="font-size:27px;">\n<tr>{th}</tr>\n{trs}\n</table>'


def slide(sid, title, lead, question, tag, body, check, memo=None):
    parts = [f'<section id="{sid}">', head(title), f'<p class="lead">{lead}</p>',
             f'<div class="bar"><p class="bar-t">{question}</p><p class="tag">{tag}</p></div>', body]
